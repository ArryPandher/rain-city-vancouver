import fs from "node:fs/promises";
import sharp from "sharp";
// Original deterministic forest drawing. No architect's photograph is sampled.
let state = 360607259;
const random = () => {
  state = (Math.imul(state, 1664525) + 1013904223) >>> 0;
  return state / 4294967296;
};
const paths = [];
function branch(x, y, angle, length, width, depth, tone) {
  const bend = (random() - 0.5) * 0.36;
  const mx = x + Math.cos(angle + bend) * length * 0.52,
    my = y + Math.sin(angle + bend) * length * 0.52;
  const xx = mx + Math.cos(angle - bend) * length * 0.48,
    yy = my + Math.sin(angle - bend) * length * 0.48;
  paths.push(
    `<path d="M${x.toFixed(2)} ${y.toFixed(2)} Q${mx.toFixed(2)} ${my.toFixed(2)} ${xx.toFixed(2)} ${yy.toFixed(2)}" stroke="rgb(${tone},${tone},${tone})" stroke-width="${width.toFixed(2)}" fill="none" stroke-linecap="round"/>`,
  );
  if (depth <= 0) return;
  const spread = 0.3 + random() * 0.4;
  branch(
    xx,
    yy,
    angle - spread,
    length * (0.62 + random() * 0.16),
    width * 0.62,
    depth - 1,
    tone,
  );
  branch(
    xx,
    yy,
    angle + spread,
    length * (0.6 + random() * 0.2),
    width * 0.64,
    depth - 1,
    tone,
  );
  if (depth > 2)
    branch(xx, yy, angle + bend, length * 0.76, width * 0.67, depth - 1, tone);
}
for (let layer = 0; layer < 3; layer++)
  for (let x = -30; x < 2080; x += 44 + random() * 70) {
    const height = 120 + random() * 130,
      tone = layer === 0 ? 189 : layer === 1 ? 132 : 73;
    branch(
      x,
      530,
      -Math.PI / 2 + (random() - 0.5) * 0.09,
      height,
      4 + random() * 9,
      5,
      tone,
    );
  }
const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="2048" height="512"><rect width="2048" height="512" fill="#e0e3df"/>${paths.join("")}</svg>`;
await fs.mkdir("public/textures/fairmont", { recursive: true });
await sharp(Buffer.from(svg))
  .webp({ quality: 92 })
  .toFile("public/textures/fairmont/forest-pattern.webp");
await fs.writeFile(
  "public/textures/fairmont/SOURCES.json",
  JSON.stringify(
    {
      file: "forest-pattern.webp",
      creator: "Rain City",
      license: "MIT",
      method:
        "Original seeded recursive-branch drawing generated by scripts/make-fairmont-pattern.mjs. Not a reproduction of James K. M. Cheng's forest photograph or Zahner's fabricated panel image.",
    },
    null,
    2,
  ) + "\n",
);
console.log(`Drew ${paths.length} original branches`);
